USE DB_T05429_BEATRIZ_NATHAN

CREATE TABLE SALE (
  ID_SALE INT AUTO_INCREMENT PRIMARY KEY,
  SALE_DATE DATE NOT NULL,
  QUANTITY INT NOT NULL,
  UNIT_PRICE DECIMAL(10,2) NOT NULL,      -- PREÇO COBRADO NA VENDA
  UNIT_COST DECIMAL(10,2) NOT NULL,       -- CUSTO DO PRODUTO NA VENDA
  PAYMENT_METHOD VARCHAR(10) NOT NULL CHECK (PAYMENT_METHOD IN ('A VISTA', 'FIADO')),
  ID_EMPLOYEE INT NOT NULL,
  ID_PRODUCT INT NOT NULL,
  ID_SUPPLIER INT NOT NULL,
  ID_CUSTOMER INT NULL,                   -- NULL = CLIENTE ANÔNIMO
  FOREIGN KEY (ID_EMPLOYEE) REFERENCES EMPLOYEE (ID_EMPLOYEE),
  FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCT (ID_PRODUCT),
  FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIER (ID_SUPPLIER),
  FOREIGN KEY (ID_CUSTOMER) REFERENCES CUSTOMER (ID_CUSTOMER)
);

-- MOVIMENTAÇÃO DE ESTOQUE (ENTRADA = COMPRA, SAÍDA = VENDA)
CREATE TABLE STOCK_MOVEMENT (
  ID_STOCK_MOVEMENT INT AUTO_INCREMENT PRIMARY KEY,
  MOVEMENT_DATE DATE NOT NULL,
  MOVEMENT_TYPE VARCHAR(10) NOT NULL CHECK (MOVEMENT_TYPE IN ('ENTRADA', 'SAÍDA')),
  QUANTITY INT NOT NULL,
  ID_PRODUCT INT NOT NULL,
  ID_SALE INT NULL,                       -- PREENCHIDO NAS SAÍDAS CAUSADAS POR UMA VENDA
  FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCT (ID_PRODUCT),
  FOREIGN KEY (ID_SALE) REFERENCES SALE (ID_SALE)
);

-- MOVIMENTAÇÃO FINANCEIRA (RECEITA = ENTRADA DE DINHEIRO, DESPESA = SAÍDA DE DINHEIRO)
CREATE TABLE FINANCIAL_MOVEMENT (
  ID_FINANCIAL_MOVEMENT INT AUTO_INCREMENT PRIMARY KEY,
  MOVEMENT_DATE DATE NOT NULL,
  MOVEMENT_TYPE VARCHAR(10) NOT NULL CHECK (MOVEMENT_TYPE IN ('RECEITA', 'DESPESA')),
  AMOUNT DECIMAL(10,2) NOT NULL,
  DESCRIPTION VARCHAR(150) NOT NULL,
  ID_SALE INT NULL,                       -- RECEITA VINDA DE UMA VENDA
  ID_SUPPLIER INT NULL,                   -- DESPESA COM FORNECEDOR
  ID_EMPLOYEE INT NULL,                   -- DESPESA COM SALÁRIO
  FOREIGN KEY (ID_SALE) REFERENCES SALE (ID_SALE),
  FOREIGN KEY (ID_SUPPLIER) REFERENCES SUPPLIER (ID_SUPPLIER),
  FOREIGN KEY (ID_EMPLOYEE) REFERENCES EMPLOYEE (ID_EMPLOYEE)
);



